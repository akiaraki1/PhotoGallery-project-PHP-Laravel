<?php

return [

    /*
    |--------------------------------------------------------------------------
    | Default Image Driver
    |--------------------------------------------------------------------------
    |
    | Здесь выбирается драйвер для обработки изображений.
    |
    | Логика:
    | 1. Если в .env указан IMAGE_DRIVER и соответствующее расширение загружено — используем его.
    | 2. Если в .env ничего не указано — автоопределение:
    |    - imagick если расширение загружено
    |    - gd в противном случае (GD есть почти везде)
    | 3. Если в .env указан драйвер, но расширение не загружено — fallback на то, что доступно.
    |
    | Поддерживаемые значения: "gd", "imagick"
    |
    */

    'default' => (function () {
        $preferred = env('IMAGE_DRIVER');

        // Если разработчик явно указал драйвер в .env и расширение загружено
        if (in_array($preferred, ['gd', 'imagick'], true) && extension_loaded($preferred)) {
            return $preferred;
        }

        // Автоопределение: imagick优先, gd как fallback
        if (extension_loaded('imagick')) {
            return 'imagick';
        }

        // GD есть почти во всех установках PHP
        if (extension_loaded('gd')) {
            return 'gd';
        }

        // Ни одного расширения нет — нельзя обработать изображения
        throw new RuntimeException(
            'Для работы с изображениями требуется PHP-расширение GD или Imagick. ' .
            'Установите одно из них.'
        );
    })(),

];
